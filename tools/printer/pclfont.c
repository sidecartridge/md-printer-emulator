/*
 * pclfont: writes rp/src/pcl/pclfont.c, the LaserJet II's built-in fonts as
 * 300 dpi bitmaps (pcl/pclfont.h), rasterised with FreeType from Courier
 * Prime, and its symbol sets, from iconv's.
 *
 * Usage:  pclfont REGULAR.ttf BOLD.ttf FALLBACK.ttf FALLBACK-BOLD.ttf OUT.c
 *         Courier Prime's regular and bold (SIL Open Font License 1.1), and
 *         DejaVu Sans Mono's (Bitstream Vera's licence) for the characters
 *         Courier Prime does not have: PC-8's Greek, mathematics and box
 *         drawing. Each font holds ASCII and every character of Roman-8, PC-8
 *         and ISO Latin 1 above it.
 */
#include <ft2build.h>
#include FT_FREETYPE_H
#include <iconv.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#define DPI 300
#define MAX_CODES 512

typedef struct {
  const char *name;
  int bold;
  int pitch;    // x 100
  int height;   // point size x 100
  int widthPt;  // the x size, point x 100: Line Printer's is narrowed
  int typeface;
} Spec;

static const Spec specs[] = {
    {"Courier 10 pitch, 12 point", 0, 1000, 1200, 1200, 3},
    {"Courier 10 pitch, 12 point, bold", 1, 1000, 1200, 1200, 3},
    {"Courier 12 pitch, 10 point", 0, 1200, 1000, 1000, 3},
    {"Courier 12 pitch, 10 point, bold", 1, 1200, 1000, 1000, 3},
    // 16.67 characters an inch is 18 dots; Courier Prime's cell is 0.6 em.
    {"Line Printer 16.67 pitch, 8.5 point", 0, 1667, 850, 720, 0},
};

static unsigned codes[MAX_CODES];
static int codeCount;

static void add_code(unsigned c) {
  if (c == 0) return;
  for (int i = 0; i < codeCount; i++) {
    if (codes[i] == c) return;
  }
  codes[codeCount++] = c;
}

// The character of byte b in a set, 0 for none.
static unsigned char_of(const char *set, unsigned char b) {
  iconv_t cd = iconv_open("UTF-32LE", set);
  char in[1] = {(char)b};
  unsigned char out[4] = {0};
  char *ip = in;
  char *op = (char *)out;
  size_t il = 1;
  size_t ol = 4;
  size_t r = iconv(cd, &ip, &il, &op, &ol);
  iconv_close(cd);
  if (r == (size_t)-1 || ol != 0) return 0;
  return out[0] | out[1] << 8 | out[2] << 16 | (unsigned)out[3] << 24;
}

static int by_code(const void *a, const void *b) {
  return (int)*(const unsigned *)a - (int)*(const unsigned *)b;
}

static void table(FILE *f, const char *name, const char *set, int first,
                  int count) {
  fprintf(f, "const uint16_t %s[%d] = {\n", name, count);
  for (int i = 0; i < count; i++) {
    unsigned c = char_of(set, (unsigned char)(first + i));
    if (c >= 0x10000) c = 0;
    fprintf(f, "%s0x%04X,%s", i % 8 == 0 ? "    " : " ", c,
            i % 8 == 7 ? "\n" : "");
  }
  fprintf(f, "};\n\n");
}

int main(int argc, char **argv) {
  if (argc != 6) {
    fprintf(stderr,
            "usage: pclfont REGULAR.ttf BOLD.ttf FALLBACK.ttf "
            "FALLBACK-BOLD.ttf OUT.c\n");
    return 2;
  }
  for (unsigned c = 0x20; c < 0x7F; c++) add_code(c);
  for (int b = 0xA0; b <= 0xFF; b++) {
    add_code(char_of("HP-ROMAN8", (unsigned char)b));
    add_code((unsigned)b);  // ISO Latin 1
  }
  for (int b = 0x80; b <= 0xFF; b++)
    add_code(char_of("CP437", (unsigned char)b));
  qsort(codes, (size_t)codeCount, sizeof(codes[0]), by_code);

  FT_Library lib;
  FT_Face faces[4];  // regular, bold, then their fallbacks
  if (FT_Init_FreeType(&lib)) return 1;
  for (int i = 0; i < 4; i++) {
    if (FT_New_Face(lib, argv[1 + i], 0, &faces[i])) {
      fprintf(stderr, "pclfont: cannot read %s\n", argv[1 + i]);
      return 1;
    }
  }
  FILE *f = fopen(argv[5], "w");
  if (!f) {
    fprintf(stderr, "pclfont: cannot write %s\n", argv[5]);
    return 1;
  }
  fprintf(f,
          "/**\n"
          " * File: pclfont.c\n"
          " * Description: The LaserJet II's built-in fonts and symbol sets "
          "(pclfont.h).\n"
          " *\n"
          " * Generated by tools/printer/pclfont.c, the glyphs rasterised at "
          "300 dpi from\n"
          " * Courier Prime, Copyright 2015 The Courier Prime Project "
          "Authors, under the\n"
          " * SIL Open Font License 1.1 (pcl/OFL.txt), and, for the "
          "characters it does\n"
          " * not have, from DejaVu Sans Mono, Copyright (c) 2003 by "
          "Bitstream, Inc.,\n"
          " * DejaVu changes in the public domain (pcl/DEJAVU-LICENSE.txt). "
          "Do not edit.\n"
          " */\n"
          "#include \"pclfont.h\"\n\n");
  table(f, "pcl_roman8", "HP-ROMAN8", 0xA0, 96);
  table(f, "pcl_pc8", "CP437", 0x80, 128);

  size_t total = 0;
  for (size_t s = 0; s < sizeof(specs) / sizeof(specs[0]); s++) {
    const Spec *sp = &specs[s];
    FT_Face face = faces[sp->bold];
    FT_Face fallback = faces[2 + sp->bold];
    for (int k = 0; k < 2; k++) {
      FT_Set_Char_Size(k ? fallback : face, sp->widthPt * 64 / 100,
                       sp->height * 64 / 100, DPI, DPI);
    }
    int fromFallback = 0;
    fprintf(f, "// %s\nstatic const uint8_t bits%zu[] = {\n", sp->name, s);
    unsigned offset = 0;
    int column = 0;
    static unsigned offsets[MAX_CODES];
    static int left[MAX_CODES], top[MAX_CODES], w[MAX_CODES], h[MAX_CODES];
    static int has[MAX_CODES];
    int advance = 0;
    for (int i = 0; i < codeCount; i++) {
      has[i] = 0;
      FT_Face from = face;
      FT_UInt index = FT_Get_Char_Index(face, codes[i]);
      if (index == 0) {
        from = fallback;
        index = FT_Get_Char_Index(fallback, codes[i]);
        if (index) fromFallback++;
      }
      if (index == 0 &&
          codes[i] == 0x02CB) {  // Roman-8's grave: neither has it
        from = face;
        index = FT_Get_Char_Index(face, '`');
      }
      if (index == 0 ||
          FT_Load_Glyph(from, index, FT_LOAD_RENDER | FT_LOAD_TARGET_MONO)) {
        if (s == 0) fprintf(stderr, "no glyph for U+%04X\n", codes[i]);
        continue;
      }
      FT_GlyphSlot g = from->glyph;
      if (codes[i] == 'M') advance = (int)(g->advance.x >> 6);
      FT_Bitmap *bm = &g->bitmap;
      has[i] = 1;
      offsets[i] = offset;
      left[i] = g->bitmap_left;
      top[i] = g->bitmap_top;
      w[i] = (int)bm->width;
      h[i] = (int)bm->rows;
      int stride = (w[i] + 7) / 8;
      for (int r = 0; r < h[i]; r++) {
        for (int k = 0; k < stride; k++) {
          fprintf(f, "%s0x%02X,", column % 12 == 0 ? "    " : " ",
                  bm->buffer[r * bm->pitch + k]);
          if (++column % 12 == 0) fprintf(f, "\n");
        }
      }
      offset += (unsigned)(stride * h[i]);
    }
    if (column % 12 != 0) fprintf(f, "\n");
    fprintf(f, "};\n\nstatic const PclGlyph glyphs%zu[] = {\n", s);
    int count = 0;
    for (int i = 0; i < codeCount; i++) {
      if (!has[i]) continue;
      fprintf(f, "    {0x%04X, %d, %d, %d, %d, %u},\n", codes[i], left[i],
              top[i], w[i], h[i], offsets[i]);
      count++;
    }
    fprintf(f, "};\n\n");
    fprintf(stderr,
            "%s: %d glyphs (%d from the fallback), %u bytes, advance %d dots\n",
            sp->name, count, fromFallback, offset, advance);
    total += offset + (size_t)count * sizeof(unsigned) * 3;
  }
  fprintf(f, "const PclFont pcl_fonts[PCL_FONTS] = {\n");
  for (size_t s = 0; s < sizeof(specs) / sizeof(specs[0]); s++) {
    const Spec *sp = &specs[s];
    fprintf(f,
            "    {%d, %d, %d, %d, sizeof(glyphs%zu) / sizeof(glyphs%zu[0]), "
            "glyphs%zu, bits%zu},\n",
            sp->pitch, sp->height, sp->bold ? 3 : 0, sp->typeface, s, s, s, s);
  }
  fprintf(f, "};\n");
  fclose(f);
  fprintf(stderr, "about %zu bytes in all\n", total);
  return 0;
}
